async function seed() {
  console.log("🚀 Starting Dual-Stream Hackathon Seeding in Neon DB...");

  let nationalCreated = 0;
  let campusCreated = 0;

  for (const h of DUAL_STREAM_HACKATHONS) {
    const existing = await prisma.hackathon.findFirst({
      where: { name: h.name },
    });

    if (existing) {
      await prisma.hackathon.update({
        where: { id: existing.id },
        data: h,
      });
      console.log(`  🔄 Updated: ${h.name} (${h.stream})`);
    } else {
      await prisma.hackathon.create({
        data: h,
      });
      console.log(`  ✨ Created: ${h.name} (${h.stream})`);
    }

    if (h.stream === "NATIONAL_AUTOMATED") {
      nationalCreated++;
    } else {
      campusCreated++;
    }
  }

  console.log(`\n🎉 Successfully seeded ${DUAL_STREAM_HACKATHONS.length} hackathons:`);
  console.log(`   - 🏆 National Automated Flagships: ${nationalCreated}`);
  console.log(`   - 🏛️ Local & Campus Sprints: ${campusCreated}`);
}

seed()
  .catch((e) => {
    console.error("❌ Seeding failed:", e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
    await pool.end();
  });
