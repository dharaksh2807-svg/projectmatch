/**
 * Pure evaluator for Prisma where-clauses generated by the route handlers.
 */
function matchesPrismaWhere(item: any, where: any): boolean {
  if (!where) return true;

  for (const [key, val] of Object.entries(where)) {
    if (val === undefined) continue;

    if (key === "AND") {
      const andList = Array.isArray(val) ? val : [val];
      const allMatch = andList.every((cond: any) => matchesPrismaWhere(item, cond));
      if (!allMatch) return false;
      continue;
    }

    if (key === "OR") {
      const orList = Array.isArray(val) ? val : [val];
      const anyMatch = orList.some((cond: any) => matchesPrismaWhere(item, cond));
      if (!anyMatch) return false;
      continue;
    }

    if (key === "NOT") {
      const notList = Array.isArray(val) ? val : [val];
      const anyMatch = notList.some((cond: any) => matchesPrismaWhere(item, cond));
      if (anyMatch) return false;
      continue;
    }

    const itemVal = item[key];

    if (typeof val === "object" && val !== null) {
      const filterObj = val as Record<string, any>;
      if ("equals" in filterObj) {
        const expected = filterObj.equals;
        if (filterObj.mode === "insensitive" && typeof itemVal === "string" && typeof expected === "string") {
          if (itemVal.toLowerCase() !== expected.toLowerCase()) return false;
        } else {
          if (itemVal !== expected) return false;
        }
      }
      if ("contains" in filterObj) {
        const needle = filterObj.contains;
        if (typeof itemVal !== "string") return false;
        if (typeof needle === "string") {
          if (filterObj.mode === "insensitive") {
            if (!itemVal.toLowerCase().includes(needle.toLowerCase())) return false;
          } else {
            if (!itemVal.includes(needle)) return false;
          }
        }
      }
      if ("not" in filterObj) {
        if (itemVal === filterObj.not) return false;
      }
      if ("notIn" in filterObj) {
        if (Array.isArray(filterObj.notIn) && filterObj.notIn.includes(itemVal)) return false;
      }
      if ("gte" in filterObj) {
        const itemDate = itemVal ? new Date(itemVal).getTime() : 0;
        const targetDate = new Date(filterObj.gte as string | number | Date).getTime();
        if (itemDate < targetDate) return false;
      }
      if ("lt" in filterObj) {
        const itemDate = itemVal ? new Date(itemVal).getTime() : 0;
        const targetDate = new Date(filterObj.lt as string | number | Date).getTime();
        if (itemDate >= targetDate) return false;
      }
    } else {
      if (itemVal !== val) return false;
    }
  }

  return true;
}

